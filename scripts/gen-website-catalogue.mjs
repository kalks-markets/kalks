#!/usr/bin/env node
// Writes apps/admin/lib/content-catalogue-website.ts from the website's slot catalogue
// (apps/trader/src/content/manifest.ts in the website repo, loaded like scripts/seed-website-content.mjs does), so
// the Back Office's Pages editor lists every website slot with its built-in default, page path and page name.
//
// USAGE
//   node scripts/gen-website-catalogue.mjs [website repo]           rewrite the file
//   node scripts/gen-website-catalogue.mjs [website repo] --check   exit 1 when the file differs
//   [website repo]: default $WEBSITE_DIR, else ../kalks-website next to the platform repo.
//   --out PATH writes elsewhere (default apps/admin/lib/content-catalogue-website.ts).

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { loadWebsiteManifest, websiteDir } from "./seed-website-content.mjs";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const argv = process.argv.slice(2);
const outIdx = argv.indexOf("--out");
const out = outIdx >= 0 ? path.resolve(argv[outIdx + 1]) : path.join(REPO, "apps/admin/lib/content-catalogue-website.ts");
const dir = websiteDir(argv.find((a, i) => !a.startsWith("--") && argv[i - 1] !== "--out"));
const { entries, pagePaths, pageLabels } = await loadWebsiteManifest(dir);

const def = (e) => (e.kind === "link" ? `${e.value.label} → ${e.value.href}` : e.kind === "image" ? e.value.src : e.value.text);
const slots = entries.map((e) => ({ surface: "website", page: e.page, slot: e.slot, kind: e.kind, label: e.label, default: def(e) }));
const json = (v) => JSON.stringify(v, null, 2);

const text = `// GENERATED by scripts/gen-website-catalogue.mjs from the website repo (apps/trader/src/content/manifest.ts).
// Do not edit: change the website's manifest and re-run the script.
import type { CatalogueSlot } from "./content-catalogue";

export const WEBSITE_SLOTS: CatalogueSlot[] = ${json(slots)};

/** page key → the website path its preview opens */
export const WEBSITE_PAGE_PATHS: Record<string, string> = ${json(pagePaths)};

/** page key → name in the Pages editor */
export const WEBSITE_PAGE_LABELS: Record<string, string> = ${json(pageLabels ?? {})};
`;

if (argv.includes("--check")) {
  const cur = existsSync(out) ? readFileSync(out, "utf8") : "";
  if (cur !== text) {
    console.error(`${path.relative(REPO, out)} is out of date: run node scripts/gen-website-catalogue.mjs`);
    process.exit(1);
  }
  console.log(`${path.relative(REPO, out)} is up to date (${slots.length} slots).`);
} else {
  writeFileSync(out, text);
  console.log(`Wrote ${path.relative(REPO, out) || out}: ${slots.length} slots on ${Object.keys(pagePaths).length} pages.`);
}
